<script>
  export let query = '';
  import { editorTools } from '$lib/editor-tools.js';
  const menuTools = new Map(editorTools.map((tool) => [tool.id, tool]));
  /** Only home tools without a bottom-toolbar entry need separate artwork. @type {Record<string, string>} */
  const homeIcons = {
    merge: '/quicktools/merge.svg', split: '/quicktools/split.svg',
    convert: '/convert.svg', compress: '/compress.svg',
    flatten: '/quicktools/flatten.svg', latex: '/brain.svg'
  };
  /** The expanded toolbar compensates for padding inside these SVGs. @param {string} id */
  function menuIconOffset(id) {
    if (id === 'select') return 1;
    if (id === 'rectangle') return -7;
    if (id === 'edit') return -3;
    if (['crossout', 'underline', 'blackout', 'whiteout'].includes(id)) return -9;
    if (['check', 'cross', 'arrow', 'line'].includes(id)) return 2;
    return -2;
  }
  /** @type {{ id: string; label: string; description?: string }[]} */
  export let tools = [];
  /** @type {(id: string) => void} */
  export let onSelect = () => {};
  $: normalized = query.trim().toLocaleLowerCase();
  $: matches = normalized ? tools.filter((tool) => `${tool.label} ${tool.description ?? ''}`.toLocaleLowerCase().includes(normalized)) : [];
</script>

{#if matches.length}
  <div class="tool-results" aria-label="Tools">
    {#each matches as tool (tool.id)}
      <button type="button" onclick={() => onSelect(tool.id)}>
        <span class="tool-icon" aria-hidden="true">
          {#if menuTools.has(tool.id)}
            <img class="menu-icon" src={`/toolbar/small/${menuTools.get(tool.id)?.smallIcon ?? tool.id}.svg`} style:transform={`translateX(calc(${menuIconOffset(tool.id)}px * var(--menu-icon-scale))) scale(var(--menu-icon-scale))`} alt="" />
          {:else}
            <img class="home-icon" src={homeIcons[tool.id]} alt="" />
          {/if}
        </span>
        <span>{tool.label}</span>
      </button>
    {/each}
  </div>
{/if}

